// Pre-generates every large page image from assets/photos, so no visitor ever waits for the server to encode one.
// Run `npm run images` after adding or changing a photo there, and commit the output.
import { mkdir, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const SOURCE = "assets/photos";
const OUTPUT = "public/images/hd";
const WIDTHS = [640, 960, 1280, 1920, 2560, 3840];

await mkdir(OUTPUT, { recursive: true });

// Encoding is slow, so only redo files older than their photo.
const isCurrent = async (output, source) => {
  try {
    return (await stat(output)).mtimeMs >= (await stat(source)).mtimeMs;
  } catch {
    return false;
  }
};

const manifest = {};
for (const file of (await readdir(SOURCE)).filter((f) => f.endsWith(".jpg")).sort()) {
  const name = path.parse(file).name;
  const input = path.join(SOURCE, file);
  const { width, height } = await sharp(input).metadata();
  const widths = WIDTHS.filter((w) => w <= width);

  for (const w of widths) {
    const resized = sharp(input).resize({ width: w });
    if (!(await isCurrent(`${OUTPUT}/${name}-${w}.avif`, input))) await resized.clone().avif({ quality: 60, effort: 4 }).toFile(`${OUTPUT}/${name}-${w}.avif`);
    if (!(await isCurrent(`${OUTPUT}/${name}-${w}.webp`, input))) await resized.clone().webp({ quality: 82 }).toFile(`${OUTPUT}/${name}-${w}.webp`);
  }
  await sharp(input).resize({ width: 1920 }).jpeg({ quality: 82, progressive: true }).toFile(`${OUTPUT}/${name}.jpg`);

  // A tiny inline preview paints with the HTML, so the space is never empty while the real file arrives.
  const blur = await sharp(input).resize({ width: 24 }).webp({ quality: 40 }).toBuffer();
  manifest[name] = { width, height, widths, blur: `data:image/webp;base64,${blur.toString("base64")}` };
  console.log(name, `${width}x${height}`);
}

await writeFile(
  "lib/hd-images.ts",
  `// Generated by scripts/build-images.mjs. Do not edit.\nexport const hdImages = ${JSON.stringify(manifest, null, 2)} as const;\n\nexport type HdImageName = keyof typeof hdImages;\n`,
);
